-- Drop previous table if recreating structure
DROP TABLE IF EXISTS public.orders CASCADE;

CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT DEFAULT '',
    address TEXT NOT NULL,
    product TEXT NOT NULL,
    total_amount NUMERIC NOT NULL DEFAULT 0,
    date TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    phone TEXT DEFAULT '',
    reference_code TEXT DEFAULT '',
    wilaya_name TEXT DEFAULT '',
    delivery_type TEXT DEFAULT 'home',
    items JSONB DEFAULT '[]'::jsonb,
    status TEXT DEFAULT 'جديد'
);

-- Indices for rapid search and sorting
CREATE INDEX IF NOT EXISTS idx_orders_name ON public.orders(name);
CREATE INDEX IF NOT EXISTS idx_orders_email ON public.orders(email);
CREATE INDEX IF NOT EXISTS idx_orders_date ON public.orders(date DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- Allow anonymous visitors (checkout form) to insert new orders
DROP POLICY IF EXISTS "Allow anon order insert" ON public.orders;
CREATE POLICY "Allow anon order insert" ON public.orders
    FOR INSERT 
    TO anon, authenticated
    WITH CHECK (true);

-- Allow reading orders (for candidate tracking and admin panel)
DROP POLICY IF EXISTS "Allow anon order select" ON public.orders;
CREATE POLICY "Allow anon order select" ON public.orders
    FOR SELECT 
    TO anon, authenticated
    USING (true);

-- Allow updating order statuses
DROP POLICY IF EXISTS "Allow anon order update" ON public.orders;
CREATE POLICY "Allow anon order update" ON public.orders
    FOR UPDATE 
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

